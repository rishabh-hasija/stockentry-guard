"""Immutable workflow envelope and persistence-generated ordering metadata."""

from collections.abc import Mapping
from dataclasses import dataclass, field
from datetime import datetime
from enum import StrEnum
from types import MappingProxyType
from uuid import UUID, uuid4

from stockentry_guard.domain.models import as_utc, utc_now

type EventValue = str | int | float | bool | None


class EventType(StrEnum):
    INVENTORY_IMPORTED = "INVENTORY_IMPORTED"
    PRODUCT_EXTRACTED = "PRODUCT_EXTRACTED"
    DUPLICATE_CHECKED = "DUPLICATE_CHECKED"
    DUPLICATE_FOUND = "DUPLICATE_FOUND"
    PRODUCT_APPROVED = "PRODUCT_APPROVED"
    PRODUCT_CREATED = "PRODUCT_CREATED"
    PRODUCT_UPDATED = "PRODUCT_UPDATED"
    PRODUCT_REJECTED = "PRODUCT_REJECTED"


@dataclass(frozen=True, slots=True)
class WorkflowEvent:
    event_type: EventType
    correlation_id: UUID
    product_id: UUID | None = None
    payload: Mapping[str, EventValue] = field(default_factory=dict)
    schema_version: int = 1
    event_id: UUID = field(default_factory=uuid4)
    occurred_at: datetime = field(default_factory=utc_now)

    def __post_init__(self) -> None:
        if not isinstance(self.event_type, EventType):
            raise ValueError("Invalid event type")
        if not isinstance(self.event_id, UUID) or not isinstance(self.correlation_id, UUID):
            raise ValueError("Event and correlation IDs must be UUIDs")
        if self.product_id is not None and not isinstance(self.product_id, UUID):
            raise ValueError("Product id must be a UUID")
        if type(self.schema_version) is not int or self.schema_version < 1:
            raise ValueError("Schema version must be a positive integer")
        object.__setattr__(self, "occurred_at", as_utc(self.occurred_at))
        object.__setattr__(self, "payload", MappingProxyType(dict(self.payload)))


@dataclass(frozen=True, slots=True)
class StoredEvent:
    """Sequence is generated by persistence; gaps are allowed."""

    sequence: int
    event: WorkflowEvent

from pathlib import Path

from alembic import command
from alembic.autogenerate import compare_metadata
from alembic.config import Config
from alembic.migration import MigrationContext
from sqlalchemy import Engine, inspect, text
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateTable

from stockentry_guard.infrastructure.persistence.database import create_database_engine
from stockentry_guard.infrastructure.persistence.models import Base


def test_migration_matches_metadata(engine: Engine) -> None:
    with engine.connect() as connection:
        assert connection.scalar(text("select version_num from alembic_version")) == "0001"
        assert compare_metadata(MigrationContext.configure(connection), Base.metadata) == []


def test_upgrade_downgrade_upgrade(tmp_path: Path) -> None:
    url = f"sqlite+pysqlite:///{(tmp_path / 'roundtrip.sqlite').as_posix()}"
    config = Config("alembic.ini")
    config.set_main_option("sqlalchemy.url", url)
    command.upgrade(config, "head")
    command.downgrade(config, "base")
    engine = create_database_engine(url)
    try:
        assert inspect(engine).get_table_names() == ["alembic_version"]
        command.upgrade(config, "head")
        assert "products" in inspect(engine).get_table_names()
    finally:
        engine.dispose()


def test_initialization_creates_directory_but_not_schema(tmp_path: Path) -> None:
    target = tmp_path / "new" / "nested" / "inventory.sqlite"
    engine = create_database_engine(f"sqlite+pysqlite:///{target.as_posix()}")
    try:
        assert target.parent.is_dir()
        assert not target.exists()
        assert inspect(engine).get_table_names() == []
    finally:
        engine.dispose()


def test_postgresql_ddl_compiles_without_driver_or_server() -> None:
    statements = [
        str(CreateTable(table).compile(dialect=postgresql.dialect()))
        for table in Base.metadata.sorted_tables
    ]
    assert "UUID" in statements[0]
    assert "TIMESTAMP WITH TIME ZONE" in statements[0]
    assert "GENERATED BY DEFAULT AS IDENTITY" in statements[1]
